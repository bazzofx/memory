"""Rebuild and check the Topics table of C:/ai/memories/index.md.

Usage:
    python C:/ai/toolbox/memory_topics.py           # check only, print the table
    python C:/ai/toolbox/memory_topics.py --write   # also rewrite the Topics section

Checks: every entry in categories/*.md has an ID with its file's prefix, IDs are
unique, tags are in the fixed list in index.md, and every ID referenced anywhere
in the memory (outside experiment sandboxes) exists. Exit code 1 on any problem.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "memories"
INDEX = ROOT / "index.md"
PREFIX = {
    "issues.md": "I", "successes.md": "S", "decisions.md": "D",
    "preferences.md": "P", "environments.md": "E", "limitations.md": "L",
    "references.md": "R", "pending.md": "T", "procedures.md": "PR",
}
ENTRY = re.compile(r"^- \*\*([A-Z]{1,2})-(\d{3})\*\* \[(\d{4}-\d{2}-\d{2})\] (.*)$")
PROC = re.compile(r"^## (PR)-(\d{3}) — (.*)$")
TAG = re.compile(r"(?<![\w&])#([a-z][a-z0-9-]*)")
REF = re.compile(r"(?<![\w-])(PR|I|S|D|P|E|L|R|T)-(\d{3})(?![\w-])")
START, END = "<!-- topics:start -->", "<!-- topics:end -->"


def vocabulary(text):
    for line in text.splitlines():
        if line.startswith("- Tags"):
            return set(TAG.findall(line))
    return set()


def entries():
    """Yield (id, file, title, tags) for every entry in categories/."""
    for path in sorted((ROOT / "categories").glob("*.md")):
        lines = path.read_text(encoding="utf-8").splitlines()
        for i, line in enumerate(lines):
            m = ENTRY.match(line)
            if m:
                rest = m.group(4)
                head, _, title = rest.partition(" — ")
                yield f"{m.group(1)}-{m.group(2)}", path.name, title, TAG.findall(head)
                continue
            m = PROC.match(line)
            if m:
                tags = TAG.findall(lines[i + 1]) if i + 1 < len(lines) else []
                yield f"PR-{m.group(2)}", path.name, m.group(3), tags


def main():
    index_text = INDEX.read_text(encoding="utf-8")
    vocab = vocabulary(index_text)
    problems = []
    if not vocab:
        problems.append("index.md has no '- Tags' line")

    seen, by_tag, highest = {}, defaultdict(list), defaultdict(int)
    for eid, fname, title, tags in entries():
        prefix, num = eid.rsplit("-", 1)
        if PREFIX.get(fname) != prefix:
            problems.append(f"{eid} in {fname}: wrong prefix (expected {PREFIX.get(fname)})")
        if eid in seen:
            problems.append(f"{eid} is used twice ({seen[eid]} and {fname})")
        seen[eid] = fname
        highest[prefix] = max(highest[prefix], int(num))
        if not tags and fname != "pending.md":
            problems.append(f"{eid} has no #tags")
        for t in tags:
            if t not in vocab:
                problems.append(f"{eid} uses unknown tag #{t}")
            by_tag[t].append(eid)

    # Every ID referenced anywhere must exist (sandboxes and experiments excluded).
    for path in ROOT.rglob("*.md"):
        rel = path.relative_to(ROOT).as_posix()
        if rel.startswith("dreams/experiments/") or rel == "index.md":
            continue
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for p, d in REF.findall(line):
                if f"{p}-{d}" not in seen:
                    problems.append(f"{rel}:{n} refers to missing {p}-{d}")

    order = lambda e: (e.split("-")[0], int(e.split("-")[1]))
    rows = ["| Tag | Entries |", "| --- | --- |"]
    for tag in sorted(by_tag):
        rows.append(f"| #{tag} | {', '.join(sorted(by_tag[tag], key=order))} |")
    nxt = ", ".join(f"{p}-{highest[p] + 1:03d}" for p in sorted(highest))
    table = "\n".join(rows) + f"\n\nNext free IDs: {nxt}. Generated by `toolbox/memory_topics.py`; don't edit by hand."

    if "--write" in sys.argv:
        if START not in index_text or END not in index_text:
            problems.append("index.md is missing the topics markers")
        else:
            head, _, tail = index_text.partition(START)
            _, _, tail = tail.partition(END)
            INDEX.write_text(f"{head}{START}\n{table}\n{END}{tail}", encoding="utf-8", newline="\n")
            print("index.md Topics rewritten")
    print(table)
    print(f"\n{len(seen)} entries, {len(by_tag)} tags in use, {len(vocab - set(by_tag))} unused tags: "
          + " ".join(sorted("#" + t for t in vocab - set(by_tag))))
    for p in problems:
        print("PROBLEM:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
